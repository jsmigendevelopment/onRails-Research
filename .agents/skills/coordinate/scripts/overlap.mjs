#!/usr/bin/env node
// No two issues in flight share a module (#255). `coordinate` step 2 runs it from your checkout of main before
// every start:
//   node overlap.mjs <issue> --in-flight <n,n,...> --repo owner/name
// --in-flight is required: pass "" when nothing is in flight, so a forgotten flag is an error, never a pass.
// It reads each issue's "Modules" (or "Modules touched") line, as the `issues` skill writes it, and the files each
// in-flight issue's branch (feat/<n>-name or fix/<n>-name) changes so far against the default branch. A clash is a
// module both issues name, or a file an in-flight branch changes inside one of the candidate's modules. An issue
// with no Modules line is "unknown": it starts only when nothing else is in flight, and nothing starts beside it.
// Shared hot spots (HOT_SPOTS below, lockfiles and files main marks `linguist-generated`) never clash on their own.
// Exit 0: the candidate can start. 1: it waits, and stderr names each clash. 2: a usage or API error. Never a pass.
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { gh, pages } from "./agent-files.mjs";
import { LOCKFILES, generated } from "./pr-rules.mjs";

// Files most changes touch on purpose and that merge cleanly, each with why it's expected to merge.
export const HOT_SPOTS = [
  [/(?:^|\/)(?:AGENTS|CLAUDE)\.md$/, "agent rules: changes add or edit separate lines"],
  [/^docs\/decisions\.md$/, "one appended row per decision"],
  [/^docs\/state\.md$/, "the loop's own notes, rewritten each sweep"],
  [/(?:^|\/)CHANGELOG\.md$/, "one line per change under Unreleased"],
  [LOCKFILES, "a lockfile: the package manager regenerates it"],
  [/(?:^|\/)[^/]+\.gen\.[A-Za-z]+$/, "generated by a tool, such as a route tree"],
];
const BRANCH = /^refs\/heads\/((?:feat|fix)\/(\d+)-[A-Za-z0-9._-]+)$/;
const MODULES = /^\s*(?:[-*]\s+)?(?:\*\*)?modules(?: touched)?(?:\*\*)?\s*:\s*(?:\*\*)?(.*)$/i;
// GitHub's compare lists at most 300 files; a branch at the cap may change more than it shows.
const COMPARE_CAP = 300;

const hot = (path, isGenerated) => HOT_SPOTS.some(([pattern]) => pattern.test(path)) || isGenerated.has(path);
const clean = (name) => name.replace(/[`*]/g, "").replace(/^\.\//, "").replace(/\/+$/, "").trim();

/** The modules an issue's body names, or null when it has no Modules line or the line is empty (unknown). */
export function modulesOf(body) {
  for (const line of String(body ?? "").split(/\r?\n/)) {
    const m = MODULES.exec(line);
    if (!m) continue;
    const names = m[1].replace(/<!--.*?-->/g, "").replace(/\([^)]*\)/g, "").split(/[,;]/).map(clean).filter(Boolean);
    return names.length ? names : null;
  }
  return null;
}

/** True when path `p` sits inside module `m`: `m`'s segments appear in order, whole, inside `p`'s. */
const covers = (m, p) => `/${p.toLowerCase()}/`.includes(`/${m.toLowerCase()}/`);

/**
 * Every clash between the candidate { n, modules } and the in-flight issues [{ n, modules, branch, files, capped }].
 * `isGenerated` is the set of paths main marks generated. Empty when the candidate can start.
 */
export function clashes(candidate, inFlight, isGenerated = new Set()) {
  const found = [];
  if (!candidate.modules && inFlight.length) {
    found.push(`#${candidate.n} has no Modules line (unknown), so it starts only when nothing else is in flight; in flight: ${inFlight.map((i) => `#${i.n}`).join(", ")}.`);
    return found;
  }
  const mine = (candidate.modules ?? []).filter((m) => !hot(m, isGenerated));
  for (const other of inFlight) {
    if (!other.modules) {
      found.push(`#${other.n} is in flight with no Modules line (unknown), so nothing starts beside it.`);
      continue;
    }
    for (const m of mine) {
      const shared = other.modules.find((o) => !hot(o, isGenerated) && (covers(m, o) || covers(o, m)));
      if (shared) found.push(`#${candidate.n} and #${other.n} both name module ${shared === m ? m : `${m} / ${shared}`}.`);
    }
    const files = (other.files ?? []).filter((f) => !hot(f, isGenerated));
    for (const m of mine) {
      const file = files.find((f) => covers(m, f));
      if (file) found.push(`#${other.n}'s branch ${other.branch} already changes ${file}, inside #${candidate.n}'s module ${m}.`);
    }
    if (other.capped) found.push(`#${other.n}'s branch ${other.branch} changes ${COMPARE_CAP} or more files, more than the API lists, so its overlap is unknown.`);
  }
  return [...new Set(found)];
}

/** The in-flight issue numbers from `--in-flight 5,8` (or `""` for none), without the candidate; null when one isn't a number. */
function inFlightArg(value, candidate) {
  const parts = String(value ?? "").split(",").map((s) => s.trim()).filter(Boolean);
  if (parts.some((s) => !/^\d+$/.test(s))) return null;
  return [...new Set(parts)].filter((s) => s !== candidate);
}

/** Each in-flight issue as clashes() reads it, from the API. */
function readInFlight(repo, numbers) {
  if (!numbers.length) return [];
  const base = JSON.parse(gh(`repos/${repo}`)).default_branch;
  if (!base) throw new Error(`GitHub gave no default branch for ${repo}`);
  const branches = new Map();
  for (const { ref } of pages(`repos/${repo}/git/matching-refs/heads`)) {
    const [, branch, n] = BRANCH.exec(ref ?? "") ?? [];
    if (n && numbers.includes(n)) branches.set(n, [...(branches.get(n) ?? []), branch]);
  }
  return numbers.map((n) => {
    const modules = modulesOf(JSON.parse(gh(`repos/${repo}/issues/${n}`)).body);
    const files = [];
    let capped = false;
    for (const branch of branches.get(n) ?? []) {
      const listed = JSON.parse(gh(`repos/${repo}/compare/${base}...${branch}`)).files ?? [];
      capped ||= listed.length >= COMPARE_CAP;
      for (const f of listed) files.push(f.filename, ...(f.previous_filename ? [f.previous_filename] : []));
    }
    return { n, modules, branch: (branches.get(n) ?? []).join(", ") || "(none yet)", files, capped };
  });
}

export function main(argv) {
  const flag = (name) => (argv.includes(name) ? argv[argv.indexOf(name) + 1] : undefined);
  const n = /^\d+$/.test(argv[0] ?? "") ? argv[0] : null;
  const repo = flag("--repo");
  const listed = flag("--in-flight");
  const numbers = listed === undefined ? null : inFlightArg(listed, n);
  if (!n || !repo || !numbers) {
    console.error("Usage: overlap.mjs <issue> --in-flight <n,n,...> --repo <owner>/<name>");
    return 2;
  }
  let found;
  let candidate;
  try {
    candidate = { n, modules: modulesOf(JSON.parse(gh(`repos/${repo}/issues/${n}`)).body) };
    const inFlight = readInFlight(repo, numbers);
    const paths = [...(candidate.modules ?? []), ...inFlight.flatMap((i) => [...(i.modules ?? []), ...i.files])];
    found = clashes(candidate, inFlight, generated([...new Set(paths)]));
  } catch (error) {
    console.error(`Couldn't read the issues or branches from the API: ${String(error.stderr || error.message).trim()}. Start nothing on this check.`);
    return 2;
  }
  if (found.length) {
    console.error(`#${n} waits; try the next ready issue.\n${found.map((line) => `- ${line}`).join("\n")}`);
    return 1;
  }
  const what = candidate.modules ? `modules ${candidate.modules.join(", ")}` : "unknown modules, alone";
  console.log(`#${n} can start (${what}): no overlap with ${numbers.length ? numbers.map((i) => `#${i}`).join(", ") : "anything, nothing is in flight"}.`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main(process.argv.slice(2));
